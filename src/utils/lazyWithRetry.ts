import { lazy, type ComponentType } from 'react'

const RELOAD_TIMESTAMP_KEY = 'adna:chunk-reload-at'
const RELOAD_COOLDOWN_MS = 10_000

function canReload(): boolean {
  try {
    const last = Number(sessionStorage.getItem(RELOAD_TIMESTAMP_KEY) || 0)
    return Date.now() - last > RELOAD_COOLDOWN_MS
  } catch {
    return true
  }
}

function markReload(): void {
  try {
    sessionStorage.setItem(RELOAD_TIMESTAMP_KEY, String(Date.now()))
  } catch {
    // sessionStorage unavailable (e.g. private browsing) - reload proceeds without the cooldown guard
  }
}

function isChunkLoadError(error: unknown): boolean {
  const message = error instanceof Error ? error.message : String(error)
  return /Failed to fetch dynamically imported module|error loading dynamically imported module|Importing a module script failed/i.test(
    message,
  )
}

/**
 * Wraps a React.lazy() dynamic import. If the chunk fails to load because
 * the hashed filename no longer exists on the server (stale build after a
 * new deploy), forces a single page reload to fetch the current bundle.
 *
 * The `never` bound (rather than `any`) relies on `never` being assignable
 * into any component's props type, so it accepts the same range of
 * components React.lazy's own `any`-bound signature does, without an
 * explicit `any` in this file's source.
 */
export function lazyWithRetry<T extends ComponentType<never>>(
  factory: () => Promise<{ default: T }>,
) {
  const wrappedFactory = (async () => {
    try {
      return await factory()
    } catch (error) {
      if (isChunkLoadError(error) && canReload()) {
        markReload()
        window.location.reload()
        return new Promise<{ default: T }>(() => {})
      }
      throw error
    }
  }) as unknown as Parameters<typeof lazy>[0]

  return lazy(wrappedFactory)
}

/**
 * Installs a window-level listener for Vite's `vite:preloadError` event,
 * which fires whenever any dynamically imported chunk fails to load -
 * including the per-route chunks generated by TanStack Router's automatic
 * code-splitting (which import route modules directly, bypassing
 * React.lazy). Forces a single reload so the browser fetches the current
 * build instead of a stale chunk left over from a previous deploy.
 */
export function installChunkErrorReload(): void {
  window.addEventListener('vite:preloadError', (event) => {
    if (!canReload()) {
      return
    }
    markReload()
    event.preventDefault()
    window.location.reload()
  })
}
